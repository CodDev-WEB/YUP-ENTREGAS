-- Número de ordem automático para cada jornada e suporte a relatórios.
-- Aplicar no SQL Editor do Supabase antes de usar o novo histórico.
alter table public.journeys
  add column if not exists order_number bigint generated by default as identity;

create unique index if not exists journeys_order_number_unique
  on public.journeys(order_number);

comment on column public.journeys.order_number is
  'Número sequencial automático da ordem de jornada, gerado pelo banco.';
