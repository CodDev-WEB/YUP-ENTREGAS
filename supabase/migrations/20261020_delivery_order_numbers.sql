-- Numeração automática das ordens de entrega.
-- O cadastro do entregador vem da conta autenticada; o veículo é escolhido
-- entre os veículos ativos cadastrados. O número da ordem é gerado no banco.
alter table public.deliveries
  add column if not exists order_number bigint generated by default as identity;

create unique index if not exists deliveries_order_number_unique
  on public.deliveries(order_number);

create or replace function public.set_delivery_order_number()
returns trigger
language plpgsql
set search_path=''
as $$
begin
  if new.order_no is null or btrim(new.order_no) = '' then
    new.order_no := 'ENT-' || lpad(new.order_number::text, 6, '0');
  end if;
  return new;
end;
$$;

drop trigger if exists deliveries_auto_order_number on public.deliveries;
create trigger deliveries_auto_order_number
before insert on public.deliveries
for each row execute function public.set_delivery_order_number();

comment on column public.deliveries.order_number is
  'Sequência numérica automática da ordem de entrega.';
